// Hardens the generated Android project. Run after `npx cap add android`
// (npm run android:init does this); safe to run again at any time (idempotent).
//  - android:allowBackup="false": no Auto Backup of app data (saved places,
//    trip history, last location in WebView storage) to the user's cloud backup.
//  - android:dataExtractionRules (Android 12+): with targetSdk >= 31, allowBackup
//    alone no longer blocks device-to-device transfer, so a rules file excludes
//    every data domain from both cloud backup and device transfer.
//  - internet + location permissions (location is requested at runtime by the
//    WebView, after Q-FLOW's own rationale screen; see src/location.js).
//  - navigation helpers: the QFlowNative plugin (text-to-speech + keep screen on, see
//    scripts/android/QFlowNativePlugin.java) is copied in and registered in MainActivity,
//    and a <queries> entry lets the app find the TTS engine on Android 11+.
//    No background-location or foreground-service permission is added.
const fs = require('fs'), path = require('path');

const PERMISSIONS = ['INTERNET', 'ACCESS_NETWORK_STATE', 'ACCESS_FINE_LOCATION', 'ACCESS_COARSE_LOCATION'];
const RULES_NAME = 'data_extraction_rules';
const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external'];
const RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/patch-android.js: exclude all app data from cloud backup and device transfer. -->
<data-extraction-rules>
    <cloud-backup>
${DOMAINS.map((d) => `        <exclude domain="${d}" path="." />`).join('\n')}
    </cloud-backup>
    <device-transfer>
${DOMAINS.map((d) => `        <exclude domain="${d}" path="." />`).join('\n')}
    </device-transfer>
</data-extraction-rules>
`;

// Pure, idempotent manifest transform (exported for tests).
function patchManifest(xml) {
  let m = xml;
  const appTag = m.match(/<application\b[^>]*>/);
  if (!appTag) throw new Error('No <application> element in AndroidManifest.xml');
  let tag = appTag[0];
  const setAttr = (t, name, value) =>
    new RegExp(`\\s${name}="[^"]*"`).test(t)
      ? t.replace(new RegExp(`(\\s${name}=)"[^"]*"`), `$1"${value}"`)
      : t.replace(/<application\b/, `<application\n        ${name}="${value}"`);
  tag = setAttr(tag, 'android:allowBackup', 'false');
  tag = setAttr(tag, 'android:dataExtractionRules', `@xml/${RULES_NAME}`);
  m = m.replace(appTag[0], tag);
  if (!m.includes('android.intent.action.TTS_SERVICE')) {
    m = m.replace('</manifest>', '    <queries>\n        <intent>\n            <action android:name="android.intent.action.TTS_SERVICE" />\n        </intent>\n    </queries>\n</manifest>');
  }
  for (const x of PERMISSIONS) {
    if (!m.includes('android.permission.' + x)) m = m.replace('</manifest>', `    <uses-permission android:name="android.permission.${x}" />\n</manifest>`);
  }
  return m;
}

// Registers the QFlowNative plugin in MainActivity (idempotent).
function patchMainActivity(java) {
  if (java.includes('registerPlugin(QFlowNativePlugin.class)')) return java;
  let j = java;
  if (!/import android\.os\.Bundle;/.test(j)) j = j.replace(/(package [^;]+;\s*)/, '$1\nimport android.os.Bundle;\n');
  if (/super\.onCreate\(/.test(j)) return j.replace(/(\s*)super\.onCreate\(/, '$1registerPlugin(QFlowNativePlugin.class);$1super.onCreate(');
  return j.replace(/public class MainActivity extends BridgeActivity\s*\{\s*\}/,
    'public class MainActivity extends BridgeActivity {\n    @Override\n    public void onCreate(Bundle savedInstanceState) {\n        registerPlugin(QFlowNativePlugin.class);\n        super.onCreate(savedInstanceState);\n    }\n}');
}

function run(androidDir) {
  const manifest = path.join(androidDir, 'app/src/main/AndroidManifest.xml');
  fs.writeFileSync(manifest, patchManifest(fs.readFileSync(manifest, 'utf8')));
  const xmlDir = path.join(androidDir, 'app/src/main/res/xml');
  fs.mkdirSync(xmlDir, { recursive: true });
  fs.writeFileSync(path.join(xmlDir, RULES_NAME + '.xml'), RULES_XML);
  const javaDir = path.join(androidDir, 'app/src/main/java/com/qflow/sih26137');
  const main = path.join(javaDir, 'MainActivity.java');
  if (fs.existsSync(main)) {
    fs.copyFileSync(path.join(__dirname, 'android', 'QFlowNativePlugin.java'), path.join(javaDir, 'QFlowNativePlugin.java'));
    fs.writeFileSync(main, patchMainActivity(fs.readFileSync(main, 'utf8')));
  }
  console.log('Manifest patched (allowBackup=false, dataExtractionRules, permissions, TTS query); QFlowNative plugin registered.');
}

if (require.main === module) run(path.join(__dirname, '..', 'android'));
module.exports = { patchManifest, patchMainActivity, run, RULES_XML, PERMISSIONS };
